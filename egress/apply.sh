#!/bin/bash
# Render + install the egress layer (nftables firewall, squid allowlist proxy, sbx-net helper).
# Idempotent. Re-run after editing egress/allowlist.txt or config.env:  sudo ./egress/apply.sh
# Note: re-applying closes all temporarily opened sandboxes.
set -euo pipefail
source "$(dirname "$(readlink -f "$0")")/../lib/common.sh"

[[ $EUID -eq 0 ]] || die "run as root: sudo $0"

# Base allowlist + allowlists of enabled agents, with overlaps pruned
# (squid refuses e.g. both "quay.io" and ".quay.io").
AGENTS_IN_ALLOWLIST=""
build_allowlist() {
  local files=("$SBX_ROOT/egress/allowlist.txt") a
  local enabled=${SBX_AGENTS_ENABLED:-$(cd "$SBX_ROOT/agents" && ls -d */ | tr -d / | tr '\n' ' ')}
  for a in $enabled; do
    [[ -f "$SBX_ROOT/agents/$a/allowlist.txt" ]] || die "agent '$a' (SBX_AGENTS_ENABLED) has no agents/$a/allowlist.txt"
    files+=("$SBX_ROOT/agents/$a/allowlist.txt")
    AGENTS_IN_ALLOWLIST+="$a "
  done
  echo "# generated by egress/apply.sh - edit egress/allowlist.txt or agents/*/allowlist.txt"
  sed -e 's/#.*//' -e 's/[[:space:]]//g' "${files[@]}" | awk 'NF' | tr 'A-Z' 'a-z' | sort -u | awk '
    { e[NR] = $0 }
    END {
      for (i = 1; i <= NR; i++) if (substr(e[i], 1, 1) == ".") wild[e[i]] = 1
      for (i = 1; i <= NR; i++) {
        d = e[i]; host = (substr(d, 1, 1) == ".") ? substr(d, 2) : d; covered = 0
        # walk parent domains: is d covered by a different wildcard entry?
        n = split(host, parts, ".")
        for (k = 1; k <= n && !covered; k++) {
          suffix = "." parts[k]; for (j = k + 1; j <= n; j++) suffix = suffix "." parts[j]
          if (suffix in wild && suffix != d) covered = 1
        }
        if (!covered) print d
      }
    }'
}
command -v squid >/dev/null || die "squid not installed (run install-host.sh)"
TARGET_USER=${SUDO_USER:-}

info "rendering /etc/sbx"
install -d -m 0755 /etc/sbx /usr/local/lib/sbx
install -d -m 0755 -o proxy -g proxy /var/log/sbx-proxy

render "$SBX_ROOT/egress/squid.conf.in"   > /etc/sbx/squid.conf
render "$SBX_ROOT/egress/egress.nft.in"   > /etc/sbx/egress.nft
build_allowlist > /etc/sbx/allowlist.squid
chmod 0644 /etc/sbx/allowlist.squid
info "allowlist: $(grep -vc '^#' /etc/sbx/allowlist.squid) domains (base + agents: ${AGENTS_IN_ALLOWLIST})"
# 192.0.2.1 (TEST-NET) placeholder keeps the ACL non-empty; never a sandbox address.
printf '# managed by sbx-net\n192.0.2.1\n' > /etc/sbx/open-clients
chmod 0644 /etc/sbx/open-clients

tmp=$(mktemp)
render "$SBX_ROOT/egress/sbx-net.in" > "$tmp";              install -m 0755 "$tmp" /usr/local/sbin/sbx-net
render "$SBX_ROOT/systemd/docker-user.sh.in" > "$tmp";      install -m 0755 "$tmp" /usr/local/lib/sbx/docker-user.sh
rm -f "$tmp"

info "installing systemd units"
install -m 0644 "$SBX_ROOT/systemd/sbx-egress.service" /etc/systemd/system/
install -m 0644 "$SBX_ROOT/systemd/sbx-proxy.service"  /etc/systemd/system/
install -d /etc/systemd/system/docker.service.d
printf '[Service]\nExecStartPost=-/usr/local/lib/sbx/docker-user.sh\n' \
  > /etc/systemd/system/docker.service.d/sbx-incus-forward.conf
cat > /etc/logrotate.d/sbx-proxy <<'EOF'
/var/log/sbx-proxy/*.log {
  weekly
  rotate 4
  compress
  missingok
  notifempty
  copytruncate
}
EOF

if [[ -n $TARGET_USER ]]; then
  info "sudoers: $TARGET_USER may run /usr/local/sbin/sbx-net without password"
  printf '%s ALL=(root) NOPASSWD: /usr/local/sbin/sbx-net\n' "$TARGET_USER" > "$tmp.sudo"
  visudo -cf "$tmp.sudo" >/dev/null || die "generated sudoers file invalid"
  install -m 0440 "$tmp.sudo" /etc/sudoers.d/sbx-net; rm -f "$tmp.sudo"
fi

# Clear leftover close-timers from previous opens
systemctl list-units --plain --no-legend 'sbx-net-close-*' 2>/dev/null | awk '{print $1}' \
  | xargs -r systemctl stop 2>/dev/null || true

systemctl daemon-reload
nft -c -f /etc/sbx/egress.nft
squid -k parse -f /etc/sbx/squid.conf >/dev/null 2>&1 || { squid -k parse -f /etc/sbx/squid.conf; die "squid config invalid"; }

systemctl enable sbx-egress.service sbx-proxy.service >/dev/null
systemctl restart sbx-egress.service
systemctl restart sbx-proxy.service
info "egress layer active: proxy ${SBX_PROXY_URL}, firewall table 'inet sbx'"
